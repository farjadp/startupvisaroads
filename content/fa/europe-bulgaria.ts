//     9 (one-year certificate), 10 (applicant plus two named team members),
//     12 (report changes within 7 days), 13 (extension by two years on a
//     progress report, incl. the 50% shareholding), 14 (free), 15 (revocation).
//   - Foreigners in the Republic of Bulgaria Act, art. 24p(1): the residence
//     permit goes to a holder of a D visa and the certificate who, AFTER the
//     D visa, became a partner or shareholder owning at least 50% of a
//     Bulgarian company in the declared business. Art. 25(1)(5): permanent
//     residence after five years' lawful continuous residence, no more than
//     30 months away.
//   - MIG's technical guidelines for NIMS (enims.egov.bg): the whole
//     application is signed with a QUALIFIED electronic signature, as a
//     detached .p7s; budget field exactly 0.00; period 12 months.
//   - Minimum wage 2026: €620.20 a month (Council of Ministers; BTA). Three
//     of them = €1,860.60. A draft decree proposes €660 from 1 Jan 2027,
//     which would make it €1,980 — re-check every January.
//   - BGN 100,000 = €51,129.19 at the fixed conversion rate 1.95583. The
//     ordinance still writes leva; Bulgaria has used the euro since 2026.
