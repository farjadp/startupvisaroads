// WHAT THE SUPPLIED DECK GETS WRONG, AND WHY THIS PAGE IS SHAPED AROUND IT
//
// The NotebookLM deck (dated 28 July 2026) sells this as «پنجره طلایی» — a
// golden window. Three corrections, each verified 2026-09-09:
//
//   1. It is built on Ministerial Direction 112, which was REVOKED by
//      Ministerial Direction 120 on 25 July 2026 — three days before the deck
//      is dated. The substance mostly carried over, but there are now five
//      priority groups, not four, and the direction covers the whole Class BX
//      including on-hand Global Talent and Distinguished Talent files.
//
//   2. Its central strategic advice — get a state nomination, it puts you in
//      Priority 2 — points at the NARROWEST lane, not the widest. In the
//      April–June 2026 round Priority 2 drew fewer than 20 invitations;
//      Priority 3 drew 192. The quarter before: 15 against 113.
//
//   3. It never says how hard this is. The Department's own invitation-round
//      figures do: 2,166 EOIs and 248 invitations for April–June 2026, 1,815
//      and 146 for January–March. Roughly one invitation per nine EOIs, and
//      the invitation — not the visa application — is the wall.
//
// THE OTHER THING THE DECK LEAVES OUT: this is not a startup visa. It is the
// Distinguished Talent visa renamed, it is assessed on the individual, and a
// team cannot apply together. A founder at idea or seed stage does not clear
// it. Australia's business-investment stream (subclass 188) closed to new
// applications in 2024, so there is no startup route underneath this one to
// fall back to. Saying that plainly is the most useful thing this page does.
//
// NO REFUND UNDERTAKING ON THIS PAGE, AND THE REASON IS DIFFERENT FROM ISRAEL.
// Every other route has an evaluating body whose approval we undertake to
// obtain — Business Finland, the Danish panel, the technopark committee. Here
// the gate is a government invitation that nobody outside the Department
// controls, with a published base rate near one in nine. An undertaking tied
// to it would be a promise we cannot keep. The page says so, and the Australia
// contract needs its own milestone definition before anything is signed.
//
// FIGURES AND THEIR SOURCES:
//   · Invitation rounds — Department of Home Affairs invitation-round page,
//     as reported 11 Aug 2026. Quarterly, and they move.
//   · Priority groups and Tier 1/Tier 2 sectors — Ministerial Direction 120,
//     in force 25 July 2026.
//   · Visa application charge — raised 1 July 2026. Secondary sources put the
//     main applicant near AUD 6,235; they disagree with each other and we
//     could not read it off Home Affairs directly, so the page carries the
//     figure with that caveat attached rather than as a settled number.
//   · Places allocated — reported at 4,300 for 2025-26. Deliberately framed
//     as NOT the constraint, because it is not.
