// FIVE CORRECTIONS THIS PAGE MAKES to the Persian material in circulation, each
// taken from the 2018 guidelines rather than from a consultancy blog:
//
//   1. The number of founders IS capped. «محدودیتی ندارد» is wrong: a maximum
//      of five Certificates of No Impediment per startup, and no more than ten
//      even in exceptional cases (Guidelines 2018, «Applications from
//      entrepreneurial teams»).
//   2. The 500-place sub-quota of the 2026–2028 Decreto Flussi is NOT reserved
//      for startup founders. It is shared with four other categories, among
//      them entrepreneurs investing €500,000 and hiring three people.
//   3. Law 193/2024 SHORTENED the base period in the special section from five
//      years to three, with an extension to five on conditions — the opposite
//      of the «تمدید از سه به پنج سال» that gets repeated.
//   4. The aggregation route is €100,000 and it must come from the applicant's
//      own resources. Neither €10,000 nor «سرمایه‌گذار» money qualifies.
//   5. The Nulla Osta expires. Three months from its issue date to collect the
//      visa, after which the file is dead and the application starts again.
//
// Two things to re-check every January: the €8,400 personal-income floor, which
// tracks the health co-payment exemption threshold, and the Decreto Flussi
// numbers, which are fixed for 2026–2028 but whose click-day calendar moves.
//
// One caveat worth carrying: the published ISV guidelines predate Law 193/2024.
// They still describe a startup as «operating no longer than 4 years» and say
// nothing about the EU SME test or the consultancy exclusion. The visa
// procedure in them is current; the startup-law definition in them is not.
