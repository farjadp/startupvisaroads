export const wage = (w: number | null, lang: Lang) => {
  if (w == null) return null;
  const v = w.toFixed(2).replace(/\.00$/, '');
  return lang === 'fa' ? `${toPersianDigits(v).replace('.', '٫')} دلار` : `$${v}`;
};
